// Package executor creates the one-shot Pods that run a single Gitea Actions
// job. A Pod is created from a runner template with a pre-registered runner
// identity; the stock runner talks to Gitea directly.
package executor

import (
	"context"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"log"
	"sort"
	"strings"

	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/client-go/kubernetes"
)

const (
	ManagedByLabel  = "app.kubernetes.io/managed-by"
	ManagedByValue  = "gitea-runner-controller"
	TemplateLabel   = "gitea-runner-controller/template"
	RunnerIDLabel   = "gitea-runner-controller/runner-id"
	RunnerNameAnnot = "gitea-runner-controller/runner-name"
)

const (
	// RunnerKey is the registration file the stock runner reads from its working
	// directory.
	RunnerKey = ".runner"
	// ConfigKey is the runner config.yaml, only present when the shared cache is
	// configured.
	ConfigKey = "config.yaml"
)

const registrationWarning = "This file is automatically generated by act-runner. Do not edit it manually unless you know what you are doing. Removing this file will cause act runner to re-register as a new runner."

// Runner is the identity returned by Gitea's runner registration API.
type Runner struct {
	ID      int64
	UUID    string
	Token   string
	Name    string
	Address string
	Labels  []string
}

type registration struct {
	Warning string   `json:"WARNING"`
	ID      int64    `json:"id"`
	UUID    string   `json:"uuid"`
	Name    string   `json:"name"`
	Token   string   `json:"token"`
	Address string   `json:"address"`
	Labels  []string `json:"labels"`
}

// Spec describes one runner Pod. Name is used for both the Pod and its config
// Secret.
type Spec struct {
	Name      string
	Template  string
	Image     string
	Labels    []string // runner labels, also written to .runner
	Resources corev1.ResourceRequirements
	Runner    Runner
	// RunnerConfig is the runner config.yaml (cache settings). Optional.
	RunnerConfig string
	// KanikoImage adds the kaniko sidecar for build templates.
	KanikoImage string
	ProxyEnv    map[string]string
	JobEnv      map[string]string
	// BuildEnv is exported to the runner and injected into image builds as ARG
	// declarations; values travel in GRC_BUILD_ENV_KEYS' matching env vars.
	BuildEnv     map[string]string
	RegistryMaps map[string]string
	// SkipDefaultRegistryFallback makes kaniko fail instead of pulling directly
	// from an upstream registry when the mapped kkRepo target does not have the
	// image.
	SkipDefaultRegistryFallback bool
	ImagePullSecret             string
	ActiveDeadlineSeconds       int64
}

// Manager owns runner Pods and their config Secrets in one namespace.
type Manager struct {
	cs        kubernetes.Interface
	namespace string
	ca        []byte
}

// New returns a Manager operating in namespace. ca, when non-nil, is added to
// every Pod's trust store.
func New(cs kubernetes.Interface, namespace string, ca []byte) *Manager {
	return &Manager{cs: cs, namespace: namespace, ca: ca}
}

const (
	// RunnerContainerName is the container whose termination means the job is over.
	// A build Pod also runs the long-lived kaniko sidecar, so the Pod phase alone
	// never becomes Succeeded/Failed.
	RunnerContainerName = "runner"
	sharedDir           = "/shared"
	dataDir             = "/data"
)

// Start creates the runner config Secret and the one-shot Pod.
func (m *Manager) Start(ctx context.Context, s Spec) error {
	if s.Name == "" || s.Image == "" || s.Runner.UUID == "" || s.Runner.Token == "" {
		return fmt.Errorf("executor: name, image and runner identity are required")
	}
	body, err := json.Marshal(registration{
		Warning: registrationWarning,
		ID:      s.Runner.ID,
		UUID:    s.Runner.UUID,
		Name:    s.Runner.Name,
		Token:   s.Runner.Token,
		Address: s.Runner.Address,
		Labels:  s.Runner.Labels,
	})
	if err != nil {
		return err
	}
	// BuildEnv is the package-proxy layer; JobEnv is the template's explicit
	// environment and wins if both name the same variable.
	env := mergeEnv(s.ProxyEnv, s.BuildEnv)
	env = mergeEnv(env, s.JobEnv)
	if keys := buildEnvKeys(s.BuildEnv, env); len(keys) > 0 {
		env["GRC_BUILD_ENV_KEYS"] = strings.Join(keys, ",")
	}
	if encoded := encodeRegistryMaps(s.RegistryMaps); encoded != "" {
		env["GRC_REGISTRY_MAPS_B64"] = encoded
	}
	if s.SkipDefaultRegistryFallback {
		env["GRC_REGISTRY_MAP_SKIP_FALLBACK"] = "1"
	}
	// The runner's workspace lives under HOME. Keeping HOME on the shared /data
	// volume means the kaniko sidecar sees the same checkout/build context.
	env["HOME"] = dataDir
	// The .runner file and optional config/CA are short-lived per-Pod data. Keep
	// them in env and let the init container materialize them; no Secret object.
	env["GRC_RUNNER_FILE"] = base64.StdEncoding.EncodeToString(body)
	if s.RunnerConfig != "" {
		env["GRC_RUNNER_CONFIG"] = base64.StdEncoding.EncodeToString([]byte(s.RunnerConfig))
	}
	if len(m.ca) > 0 {
		env["GRC_CA_PEM"] = base64.StdEncoding.EncodeToString(m.ca)
	}
	runnerEnv := envVars(env)
	if s.KanikoImage != "" {
		runnerEnv = append(runnerEnv,
			corev1.EnvVar{Name: "GRC_SHARED", Value: sharedDir},
		)
	}
	runner := corev1.Container{
		Name:            RunnerContainerName,
		Image:           s.Image,
		ImagePullPolicy: corev1.PullAlways,
		WorkingDir:      dataDir,
		Resources:       s.Resources,
		Env:             runnerEnv,
		Command: []string{"sh", "-c", `set -e
cd /data
if [ -f /data/config.yaml ]; then
  exec /usr/local/bin/gitea-runner daemon --once --config /data/config.yaml
fi
exec /usr/local/bin/gitea-runner daemon --once`},
		VolumeMounts: []corev1.VolumeMount{
			{Name: "runner-data", MountPath: dataDir},
		},
	}

	volumes := []corev1.Volume{
		{Name: "runner-data", VolumeSource: corev1.VolumeSource{EmptyDir: &corev1.EmptyDirVolumeSource{}}},
	}
	initContainers := []corev1.Container{{
		Name:            "runner-files",
		Image:           s.Image,
		ImagePullPolicy: corev1.PullAlways,
		Env: []corev1.EnvVar{
			{Name: "GRC_RUNNER_FILE", Value: env["GRC_RUNNER_FILE"]},
			{Name: "GRC_RUNNER_CONFIG", Value: env["GRC_RUNNER_CONFIG"]},
		},
		Command: []string{"sh", "-c", `set -e
mkdir -p /data
printf '%s' "$GRC_RUNNER_FILE" | base64 -d > /data/.runner
chmod 0600 /data/.runner
if [ -n "${GRC_RUNNER_CONFIG:-}" ]; then printf '%s' "$GRC_RUNNER_CONFIG" | base64 -d > /data/config.yaml; fi`},
		VolumeMounts: []corev1.VolumeMount{
			{Name: "runner-data", MountPath: dataDir},
		},
	}}

	var sidecar []corev1.Container
	if s.KanikoImage != "" {
		volumes = append(volumes, corev1.Volume{
			Name: "shared", VolumeSource: corev1.VolumeSource{EmptyDir: &corev1.EmptyDirVolumeSource{}}})
		initContainers = append(initContainers, corev1.Container{
			Name:            "shared-dir",
			Image:           s.KanikoImage,
			ImagePullPolicy: corev1.PullAlways,
			Command:         []string{"sh", "-c", "mkdir -p " + sharedDir + "/req " + sharedDir + "/kaniko/.docker " + dataDir},
			VolumeMounts: []corev1.VolumeMount{
				{Name: "shared", MountPath: sharedDir},
				{Name: "runner-data", MountPath: dataDir},
			},
		})
		runner.VolumeMounts = append(runner.VolumeMounts, corev1.VolumeMount{Name: "shared", MountPath: sharedDir})
		kanikoEnv := mergeEnv(s.ProxyEnv, s.JobEnv)
		kanikoEnv["HOME"] = dataDir
		sidecar = []corev1.Container{{
			Name:            "kaniko",
			Image:           s.KanikoImage,
			ImagePullPolicy: corev1.PullAlways,
			Resources:       s.Resources,
			Env:             envVars(kanikoEnv),
			Command:         []string{"sh", "-c", kanikoSidecarScript},
			VolumeMounts: []corev1.VolumeMount{
				{Name: "shared", MountPath: sharedDir},
				{Name: "runner-data", MountPath: dataDir},
			},
		}}
	}

	noServiceAccount := false
	pod := &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{Name: s.Name, Namespace: m.namespace,
			Labels: podLabels(s), Annotations: map[string]string{RunnerNameAnnot: s.Runner.Name}},
		Spec: corev1.PodSpec{
			RestartPolicy:                corev1.RestartPolicyNever,
			AutomountServiceAccountToken: &noServiceAccount,
			ActiveDeadlineSeconds:        positiveOrNil(s.ActiveDeadlineSeconds),
			ImagePullSecrets:             pullSecrets(s.ImagePullSecret),
			InitContainers:               initContainers,
			Containers:                   append([]corev1.Container{runner}, sidecar...),
			Volumes:                      volumes,
		},
	}
	if len(m.ca) > 0 {
		injectCA(&pod.Spec, s.Image, m.ca)
	}
	if _, err := m.cs.CoreV1().Pods(m.namespace).Create(ctx, pod, metav1.CreateOptions{}); err != nil {
		if apierrors.IsAlreadyExists(err) {
			return fmt.Errorf("runner pod %s already exists", s.Name)
		}
		return fmt.Errorf("create runner pod: %w", err)
	}
	log.Printf("executor: started %s template=%s runner=%d", s.Name, s.Template, s.Runner.ID)
	return nil
}

func podLabels(s Spec) map[string]string {
	return map[string]string{
		ManagedByLabel: ManagedByValue,
		TemplateLabel:  s.Template,
		RunnerIDLabel:  fmt.Sprintf("%d", s.Runner.ID),
	}
}

func envVars(m map[string]string) []corev1.EnvVar {
	if len(m) == 0 {
		return nil
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := make([]corev1.EnvVar, 0, len(keys))
	for _, k := range keys {
		out = append(out, corev1.EnvVar{Name: k, Value: m[k]})
	}
	return out
}

// mergeEnv overlays values on base. Job/template env intentionally wins over the
// platform proxy env: an operator who sets HTTP_PROXY in a template means it.
func mergeEnv(base, overlay map[string]string) map[string]string {
	out := make(map[string]string, len(base)+len(overlay))
	for k, v := range base {
		out[k] = v
	}
	for k, v := range overlay {
		out[k] = v
	}
	return out
}

// buildEnvKeys returns the sorted buildEnv names that still have a non-empty
// value after template overrides. The shim reads their actual values from the
// runner environment, so a step-level override is honored automatically.
func buildEnvKeys(buildEnv, merged map[string]string) []string {
	keys := make([]string, 0, len(buildEnv))
	for k := range buildEnv {
		if merged[k] != "" {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	return keys
}

// encodeRegistryMaps serializes mappings as base64 lines "registry=target",
// which the POSIX shell shim can decode without a JSON parser.
func encodeRegistryMaps(maps map[string]string) string {
	if len(maps) == 0 {
		return ""
	}
	keys := make([]string, 0, len(maps))
	for k := range maps {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	for _, k := range keys {
		b.WriteString(k)
		b.WriteByte('=')
		b.WriteString(maps[k])
		b.WriteByte('\n')
	}
	return base64.StdEncoding.EncodeToString([]byte(b.String()))
}

func pullSecrets(name string) []corev1.LocalObjectReference {
	if name == "" {
		return nil
	}
	return []corev1.LocalObjectReference{{Name: name}}
}

func positiveOrNil(v int64) *int64 {
	if v <= 0 {
		return nil
	}
	return &v
}

// List returns the runner Pods managed by this controller.
func (m *Manager) List(ctx context.Context) ([]corev1.Pod, error) {
	pods, err := m.cs.CoreV1().Pods(m.namespace).List(ctx, metav1.ListOptions{
		LabelSelector: ManagedByLabel + "=" + ManagedByValue,
	})
	if err != nil {
		return nil, err
	}
	return pods.Items, nil
}

// Delete removes the runner Pod.
func (m *Manager) Delete(ctx context.Context, name string) error {
	if err := m.cs.CoreV1().Pods(m.namespace).Delete(ctx, name, metav1.DeleteOptions{}); err != nil && !apierrors.IsNotFound(err) {
		return err
	}
	return nil
}

// Phase returns the Pod phase, or "" when the Pod no longer exists.
func (m *Manager) Phase(ctx context.Context, name string) (corev1.PodPhase, error) {
	pod, err := m.cs.CoreV1().Pods(m.namespace).Get(ctx, name, metav1.GetOptions{})
	if apierrors.IsNotFound(err) {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	return pod.Status.Phase, nil
}

const caBundleDir = "/etc/grc-ca"
const caBundleFile = caBundleDir + "/ca-certificates.crt"
const caBundleVol = "grc-ca-bundle"

const caBundleScript = `out=` + caBundleFile + `
: > "$out"
[ -f /etc/ssl/certs/ca-certificates.crt ] && cat /etc/ssl/certs/ca-certificates.crt >> "$out"
printf '%s' "$GRC_CA_PEM" | base64 -d >> "$out"
[ -s "$out" ] || { echo "no CA material" >&2; exit 1; }`

func injectCA(ps *corev1.PodSpec, image string, caPEM []byte) {
	ps.Volumes = append(ps.Volumes,
		corev1.Volume{Name: caBundleVol, VolumeSource: corev1.VolumeSource{EmptyDir: &corev1.EmptyDirVolumeSource{}}},
	)
	ps.InitContainers = append(ps.InitContainers, corev1.Container{
		Name: "ca-bundle", Image: image, ImagePullPolicy: corev1.PullAlways,
		Env: []corev1.EnvVar{{
			Name:  "GRC_CA_PEM",
			Value: base64.StdEncoding.EncodeToString(caPEM),
		}},
		Command: []string{"sh", "-c", caBundleScript},
		VolumeMounts: []corev1.VolumeMount{
			{Name: caBundleVol, MountPath: caBundleDir},
		},
	})
	env := []corev1.EnvVar{
		{Name: "SSL_CERT_FILE", Value: caBundleFile},
		{Name: "SSL_CERT_DIR", Value: "/etc/ssl/certs"},
		{Name: "CURL_CA_BUNDLE", Value: caBundleFile},
		{Name: "GIT_SSL_CAINFO", Value: caBundleFile},
		{Name: "NODE_EXTRA_CA_CERTS", Value: caBundleFile},
		{Name: "REQUESTS_CA_BUNDLE", Value: caBundleFile},
	}
	for i := range ps.Containers {
		ps.Containers[i].VolumeMounts = append(ps.Containers[i].VolumeMounts,
			corev1.VolumeMount{Name: caBundleVol, MountPath: caBundleDir, ReadOnly: true})
		ps.Containers[i].Env = append(ps.Containers[i].Env, env...)
	}
}

// kanikoSidecarScript is copied from the previous architecture: the runner's
// docker shim hands build requests to this container through /shared.
const kanikoSidecarScript = `set -u
shared=` + sharedDir + `
mkdir -p "$shared/req"
while true; do
  for d in "$shared"/req/*/; do
    [ -f "$d/go" ] || continue
    [ -f "$d/done" ] && continue
    set --
    while IFS= read -r a; do set -- "$@" "$a"; done < "$d/args"
    mkdir -p /kaniko/.docker
    [ -f "$shared/kaniko/.docker/config.json" ] && cp "$shared/kaniko/.docker/config.json" /kaniko/.docker/config.json
    if [ -f "$d/env" ]; then set -a; . "$d/env"; set +a; fi
    /kaniko/executor "$@" > "$d/log" 2>&1
    echo $? > "$d/rc"
    : > "$d/done"
  done
  sleep 1
done`
